#!/usr/bin/env python3
"""Seed the retail network so ONE storefront order can be quoted, sourced and turned into a purchase order.

WHY THIS EXISTS
---------------
The ten retail-network services are deployed and EMPTY: no vendor, no nodes, no
service areas, no catalogue, no stock. A checkout therefore finds no offer and no
purchase order is ever issued. The fleet's own supply loop (network-fulfillment,
ADR 0027: node profile + inventory feed) will feed the network one day; until it
does, this script stands in for it. It speaks ONLY the services' public REST APIs
(through Kong), exactly as a partner manager / network planner / vendor would.

WHAT IT SEEDS (input: scripts/data/retail-network-seed.json), in dependency order
-------------------------------------------------------------------------------
  1. node-topology         region, delivery station(s) (network-operated, activated)
  2. vendor-connectivity   vendor V-WS (POST /vendors), the fulfillment node with
                           vendorNodeCode = the fleet site code (SIM1), its first
                           operational profile (PUT /vendor/nodes/{id}/profile)
  3. node-topology         activation of the fulfillment node, lane node -> station,
                           service-area prefixes -> station
  4. last-mile-delivery    daily delivery waves at the station (order-sourcing has no
                           path to a customer without a wave; they are dated, so
                           re-run now and then to extend the horizon)
  5. offer-availability    catalogue items (fleet SKUs) and one listing per item and node
  6. vendor-connectivity   inventory feed for the node (POST /vendor/inventory,
                           fullUpdate=true, basis PHYSICAL), so listings are purchasable
  7. delivery-promise      NOTHING to seed: the promise policy is the built-in default
                           (v0) in code. The script only reads it.
Linehaul PICKUP departures are generated by linehaul-transportation itself when the
node is ACTIVE with a profile and has an outbound lane; the script only reads them.

IDEMPOTENCY (every write is an upsert by NATURAL KEY: GET first, write only if needed)
-------------------------------------------------------------------------------------
  region                code                       absent -> POST; 409 region-code-taken = exists
  delivery station      type+region+postal code    absent -> POST, PROPOSED -> :activate
  vendor                vendorId                   absent -> POST /vendors
  fulfillment node      vendorRef (V-WS, SIM1)     absent -> POST /vendor/nodes (async, polled);
                                                   an existing node is ADOPTED, never registered twice
  node profile          profileRevision            declared only if the node's revision is LOWER than
                                                   the data file's; a higher one (the fleet's own
                                                   declaration, ADR 0027) is left alone
  lane                  origin+destination         an OPEN lane = exists; 409 duplicate-lane = exists
  service area          postal prefix              same station = exists; another station = reported
                                                   and left alone (--reassign bumps the version)
  wave                  station+date+induct cutoff existing non-cancelled wave = exists
  catalogue item        title                      absent -> POST (the network generates the id)
  listing               item+node                  absent -> POST; 409 duplicate-listing = exists
  inventory             listing never fed          fed once; a listing that already carries a feed
                                                   (the seed's or the fleet's) is NOT overwritten
                                                   unless --restock
A second run against an unchanged cluster sends no write at all.
The Idempotency-Key of every write is scoped to the run (seed-rn:<run id>:...): a retry
inside the run replays, a later run is a fresh attempt (a key that replayed a FAILED
asynchronous transaction would otherwise block every retry for 24 hours).

USAGE
-----
    python3 scripts/seed-retail-network.py --dry-run          # plan: GETs only, nothing written
    python3 scripts/seed-retail-network.py                    # seed, then verify
    python3 scripts/seed-retail-network.py --verify           # read-only PASS/FAIL table
    python3 scripts/seed-retail-network.py --verify --quote   # also ask for a delivery quote
                                                              # (POST /delivery-offers:quote: persists
                                                              # a short-lived offer, the only non-GET)
    python3 scripts/seed-retail-network.py --emit-translation # READ-ONLY: the productTranslation block for
                                                              # helm-values/network-fulfillment.yaml, YAML only on stdout
    python3 scripts/seed-retail-network.py --check-translation helm-values/network-fulfillment.yaml
                                                              # READ-ONLY: does that file's dictionary match the network?

--base-url defaults to $RETAIL_NETWORK_BASE_URL or http://localhost:8000/api (Kong); each context
is reached at <base-url>/<context>, e.g. http://localhost:8000/api/node-topology.

THE PRODUCT DICTIONARY OF network-fulfillment (--emit-translation, --check-translation)
---------------------------------------------------------------------------------------
network-fulfillment turns the networkProductId of a purchase-order line into a fleet SKU through ONE
dictionary, `productTranslation.mappings` of helm-values/network-fulfillment.yaml; in live mode the
networkProductId is the network's LISTING id. The network generates those ids when this script creates
the listings, so the dictionary can only be read back from the network, and a reseeded network
(fresh cluster, new ids) leaves it silently stale. Both modes issue GET requests only (the client
refuses any other verb) and stand alone: no other mode flag combines with them.
  --emit-translation          for every fulfillment node of the data file, prints on stdout the block to paste at
                              the top level of the values file, sorted by sku then listing id. Progress goes to
                              stderr. A node or a SKU that has no listing prints NOTHING on stdout, one stderr line
                              per problem, exit 1: a partial dictionary must never look complete.
  --check-translation PATH    reads productTranslation.mappings of PATH (a strict hand parser: stdlib has no
                              YAML) and compares it with what --emit-translation would print. Equal: one line
                              "dictionary matches the network (N mappings)", exit 0. Otherwise the diff (missing /
                              extra / wrong listing / wrong sku) on stdout, exit 1. Stub fixture ids (*-LOCAL-<n>)
                              are flagged: they must not survive the flip to live.

EXIT CODES
----------
  0  everything is seeded (or would be, with --dry-run) and verification passes
  1  at least one write failed or was skipped because of a failure, or a verification check failed;
     with --emit-translation / --check-translation: the dictionary cannot be built (a node or SKU
     without a listing) or the values file differs from the network
  2  a service is unreachable or does not answer JSON, or the data file is unusable (nothing written);
     with --check-translation: the values file is unreadable or not the shape the parser accepts

Stdlib only (zoneinfo needs the system time zone database).
"""

