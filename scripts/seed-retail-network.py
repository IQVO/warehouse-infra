class SetupError(RuntimeError):
    """A service or the data file is unusable: abort (exit 2)."""


class StepError(RuntimeError):
    """One item cannot be seeded: recorded as a failure, the other items go on."""


class Skip(Exception):
    """A step needs something an earlier failed step should have produced."""


# ------------------------------------------------------------------ HTTP
class Api:
    """A tiny JSON-over-HTTP client. 4xx/5xx are returned, never raised; 429 honours Retry-After."""

    def __init__(self, base_url: str, timeout: float = 15.0, retries: int = 2, delay_s: float = 0.5):
        self.base, self.timeout, self.retries, self.delay_s = base_url.rstrip("/"), timeout, retries, delay_s

    def call(self, method: str, path: str, body=None, key: str | None = None):
        if body is not None:
            data = json.dumps(body).encode()
        else:
            data = b"" if method in ("POST", "PUT") else None
        attempt = throttled = 0
        while True:
            req = urllib.request.Request(self.base + path, data=data, method=method)
            req.add_header("Accept", "application/json")
            if body is not None:
                req.add_header("Content-Type", "application/json")
            if key:
                req.add_header("Idempotency-Key", key)
            try:
                with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                    return resp.status, _decode(resp.read())
            except urllib.error.HTTPError as e:
                status, decoded = e.code, _decode(e.read())
                if status == 429 and throttled < 5:
                    throttled += 1
                    time.sleep(min(_retry_after(e.headers.get("Retry-After")), 10.0))
                    continue
                if status >= 500 and method == "GET" and attempt < self.retries:
                    attempt += 1
                    time.sleep(self.delay_s)
                    continue
                return status, decoded
            except (urllib.error.URLError, TimeoutError, ConnectionError) as e:
                if attempt < self.retries:
                    attempt += 1
                    time.sleep(self.delay_s)
                    continue
                raise SetupError(f"{method} {self.base + path}: {getattr(e, 'reason', e)}") from e


def _decode(raw: bytes):
    if not raw:
        return None
    try:
        return json.loads(raw)
    except ValueError:
        return {"raw": raw.decode(errors="replace")[:200]}


def _retry_after(value) -> float:
    try:
        return max(0.0, float(value))
    except (TypeError, ValueError):
        return 1.0


def slug(body) -> str:
    """The problem-type slug of an RFC 9457 body (a bare slug or the last segment of a URL)."""
    t = body.get("type") if isinstance(body, dict) else ""
    return str(t or "").rstrip("/").rsplit("/", 1)[-1]


def short(body, n: int = 160) -> str:
    text = json.dumps(body, sort_keys=True) if not isinstance(body, str) else body
    return text if len(text) <= n else text[: n - 3] + "..."


def q(value) -> str:
    return urllib.parse.quote(str(value), safe="")


def qs(**params) -> str:
    items = {k: v for k, v in params.items() if v is not None}
    return "?" + urllib.parse.urlencode(items) if items else ""


def is_dry(node_id) -> bool:
    return str(node_id).startswith(DRY)


def iso(t: dt.datetime) -> str:
    return t.astimezone(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def parse_ts(text: str) -> dt.datetime:
    return dt.datetime.fromisoformat(str(text).replace("Z", "+00:00")).astimezone(dt.timezone.utc)


def tzinfo(name: str):
    try:
        return ZoneInfo(name)
    except (ZoneInfoNotFoundError, ValueError, TypeError) as e:
        raise SetupError(f"unknown time zone {name!r} (no system tz database? try: pip install tzdata)") from e


def wave_times(day: dt.date, tz, waves: dict):
    """(induct cutoff, window start, window end) of the wave of a local service date, in UTC."""

    def at(hhmm: str) -> dt.datetime:
        h, m = (int(x) for x in hhmm.split(":"))
        return dt.datetime(day.year, day.month, day.day, h, m, tzinfo=tz).astimezone(dt.timezone.utc)

    return at(waves["inductCutoffLocal"]), at(waves["windowStartLocal"]), at(waves["windowEndLocal"])


# ------------------------------------------------------------------ data file
def load_config(path: str = DATA_FILE) -> dict:
    try:
        with open(path, encoding="utf-8") as f:
            cfg = json.load(f)
    except (OSError, ValueError) as e:
        raise SetupError(f"cannot read data file {path}: {e}") from e
    try:
        _validate(cfg)
    except (KeyError, TypeError, ValueError, AttributeError) as e:
        raise SetupError(f"invalid data file {path}: {type(e).__name__}: {e}") from e
    return cfg


def _validate(cfg: dict) -> None:
    for k in ("vendor", "region", "deliveryStations", "fulfillmentNodes", "waves", "catalog"):
        if k not in cfg:
            raise KeyError(k)
    cfg["vendor"]["vendorId"], cfg["vendor"]["name"], cfg["vendor"]["ackWindowMinutes"]  # noqa: B018
    cfg["region"]["code"], cfg["region"]["name"]  # noqa: B018
    stations = {s["code"] for s in cfg["deliveryStations"]}
    if not stations or len(stations) != len(cfg["deliveryStations"]):
        raise ValueError("deliveryStations: at least one, codes unique")
    for s in cfg["deliveryStations"]:
        tzinfo(s["timezone"])
        s["postalCode"], s["countryCode"], s["serviceAreaPrefixes"]  # noqa: B018
    codes = [f["vendorNodeCode"] for f in cfg["fulfillmentNodes"]]
    if not codes or len(set(codes)) != len(codes):
        raise ValueError("fulfillmentNodes: at least one, vendorNodeCode unique")
    for f in cfg["fulfillmentNodes"]:
        f["nodeType"], f["timezone"], f["postalCode"], f["countryCode"]  # noqa: B018
        if f["profile"]["profileRevision"] < 1:
            raise ValueError(f"{f['vendorNodeCode']}: profileRevision must be >= 1")
        if f.get("lane") and f["lane"]["toStation"] not in stations:
            raise ValueError(f"{f['vendorNodeCode']}: lane.toStation is not a deliveryStations code")
    for k in ("days", "inductCutoffLocal", "windowStartLocal", "windowEndLocal", "stopCapacity"):
        cfg["waves"][k]  # noqa: B018
    titles, skus = set(), set()
    for it in cfg["catalog"]:
        for k in ("sku", "title", "lengthMm", "widthMm", "heightMm", "weightG", "hazmat", "fragile"):
            it[k]  # noqa: B018
        if it["availableQty"] < 1:
            raise ValueError(f"{it['sku']}: availableQty must be > 0 (a listing is purchasable only with stock)")
        if it["title"] in titles or it["sku"] in skus:
            raise ValueError(f"{it['sku']}: duplicate sku or title (the title is the natural key)")
        titles.add(it["title"])
        skus.add(it["sku"])


# ------------------------------------------------------------------ the seed
class Seeder:
    def __init__(self, cfg: dict, apis: dict, *, now: dt.datetime, dry_run=False, restock=False, reassign=False,
                 settle_s=5.0, tx_timeout_s=60.0, tx_poll_s=1.0, sleep=time.sleep, clock=time.monotonic):
        self.cfg, self.now = cfg, now
        self.nt, self.vc, self.oa = apis["node-topology"], apis["vendor-connectivity"], apis["offer-availability"]
        self.lm, self.dp, self.lh = apis["last-mile-delivery"], apis["delivery-promise"], apis["linehaul-transportation"]
        self.dry_run, self.restock, self.reassign = dry_run, restock, reassign
        self.settle_s, self.tx_timeout_s, self.tx_poll_s, self.sleep, self.clock = settle_s, tx_timeout_s, tx_poll_s, sleep, clock
        self.run_id = now.strftime("%Y%m%dT%H%M%SZ")
        self.vendor_id = cfg["vendor"]["vendorId"]
        self.counts = {"created": 0, "updated": 0, "unchanged": 0}
        self.failures: list[str] = []
        self.skipped = 0
        self.fresh = False       # something was created/activated in this run: the event-fed views need a moment
        self.state = {"region_id": None, "ds": {}, "fc": {}, "items": {}, "listings": {}}

    # ---- plumbing
    def key(self, *parts: str) -> str:
        k = ":".join(("seed-rn", self.run_id, *parts))
        return k if len(k) <= 120 else f"seed-rn:{self.run_id}:{hashlib.sha1(k.encode()).hexdigest()}"

    def same(self, label: str, note: str = "") -> None:
        print(f"  exists   {label}{('  (' + note + ')') if note else ''}")
        self.counts["unchanged"] += 1

    def fail(self, msg: str) -> None:
        print(f"  FAILED   {msg}")
        self.failures.append(msg)

    def read(self, api: Api, path: str, allow_404=False) -> Any:
        status, body = api.call("GET", path)
        if status == 200:
            return body
        if status == 404 and allow_404:
            return None
        raise StepError(f"GET {path} -> {status} {short(body)}")

    def write(self, verb: str, label: str, api: Api, method: str, path: str, body, key: str, ok=(200, 201, 202),
              tolerate=()):
        """One write. Returns (outcome, body): outcome done | tolerated (409/422 = already so) | dry."""
        if self.dry_run:
            print(f"  would {verb:<8} {label}")
            self.counts["created" if verb == "CREATE" else "updated"] += 1
            return "dry", None
        status, resp = api.call(method, path, body, key)
        if status in ok:
            print(f"  {verb:<8} {label}")
            self.counts["created" if verb == "CREATE" else "updated"] += 1
            return "done", resp
        if status in (409, 422) and slug(resp) in tolerate:
            self.same(label, f"{status} {slug(resp)}")
            return "tolerated", resp
        raise StepError(f"{label}: {method} {path} -> {status} {short(resp)}")

    def pages(self, api: Api, path: str, params: dict, field: str) -> list:
        out, after = [], None
        for _ in range(1000):
            body = self.read(api, path + qs(**params, limit=500, after=after))
            if not isinstance(body, dict):
                raise StepError(f"GET {path}: unexpected answer {short(body)}")
            out += body.get(field, [])
            after = body.get("nextCursor")
            if not after:
                return out
        raise StepError(f"GET {path}: more than 1000 pages")

    def wait_tx(self, label: str, tx_id: str) -> dict:
        """Poll an asynchronous vendor write to a terminal state."""
        deadline = self.clock() + self.tx_timeout_s
        while True:
            tx = self.read(self.vc, f"/vendor/transactions/{q(tx_id)}" + qs(vendorId=self.vendor_id))
            if isinstance(tx, dict) and tx.get("status") in ("SUCCESS", "FAILURE"):
                return tx
            if self.clock() >= deadline:
                raise StepError(f"{label}: transaction {tx_id} still PROCESSING after {self.tx_timeout_s:.0f}s (re-run later)")
            self.sleep(self.tx_poll_s)

    def vendor_write(self, verb: str, label: str, path: str, method: str, body: dict, key: str, tolerate_codes=()):
        """An asynchronous vendor write (202 + transactionId), polled. Returns the SUCCESS/tolerated transaction."""
        if self.dry_run:
            print(f"  would {verb:<8} {label}")
            self.counts["created" if verb == "CREATE" else "updated"] += 1
            return None
        status, resp = self.vc.call(method, path, body, key)
        if status != 202 or not isinstance(resp, dict) or "transactionId" not in resp:
            raise StepError(f"{label}: {method} {path} -> {status} {short(resp)}")
        tx = self.wait_tx(label, resp["transactionId"])
        codes = [e.get("code") for e in tx.get("errors") or []]
        if tx["status"] == "SUCCESS":
            print(f"  {verb:<8} {label}  (tx {resp['transactionId']})")
            self.counts["created" if verb == "CREATE" else "updated"] += 1
            return tx
        if codes and all(c in tolerate_codes for c in codes):
            self.same(label, ", ".join(codes))
            return tx
        raise StepError(f"{label}: transaction {resp['transactionId']} FAILED {short(tx.get('errors'))}")

    # ---- finders (natural keys); shared with verify
    def find_region(self) -> Any:
        regions = self.read(self.nt, "/regions")
        if not isinstance(regions, list):
            raise StepError(f"GET /regions: unexpected answer {short(regions)}")
        return next((r for r in regions if r.get("code") == self.cfg["region"]["code"]), None)

    def find_station(self, ds: dict, region_id: str) -> Any:
        if is_dry(region_id):
            return None
        body = self.read(self.nt, "/nodes" + qs(type="DELIVERY_STATION", region=region_id))
        return next((n for n in body.get("nodes", []) if n.get("status") != "RETIRED"
                     and (n.get("location") or {}).get("postalCode") == ds["postalCode"]
                     and (n.get("location") or {}).get("countryCode") == ds["countryCode"]), None)

    def find_fc(self, fc: dict) -> Any:
        body = self.read(self.nt, "/nodes" + qs(type="FULFILLMENT_CENTER"))
        for n in body.get("nodes", []):
            ref = n.get("vendorRef") or {}
            if (ref.get("vendorId") == self.vendor_id and ref.get("vendorNodeCode") == fc["vendorNodeCode"]
                    and n.get("status") != "RETIRED"):
                return self.read(self.nt, f"/nodes/{q(n['nodeId'])}")      # the single read carries the profile
        return None

    def catalog_by_title(self) -> dict:
        return {it["title"]: it for it in self.pages(self.oa, "/catalog", {}, "items")}

    def open_lane(self, origin: str, destination: str) -> Any:
        body = self.read(self.nt, "/lanes" + qs(origin=origin, destination=destination))
        return next((l for l in body.get("lanes", []) if l.get("status") == "OPEN"), None)

    # ---- stage 0: reachability
    def preflight(self) -> None:
        probes = {
            self.nt: "/regions",
            self.vc: f"/vendors/{q(self.vendor_id)}",
            self.oa: "/catalog" + qs(limit=1),
            self.lm: "/waves" + qs(stationNodeId="preflight", serviceDate="2000-01-01"),
            self.dp: "/promise-policies/current",
            self.lh: "/departures" + qs(limit=1),
        }
        for api, path in probes.items():
            status, body = api.call("GET", path)
            if status >= 500 or not isinstance(body, (dict, list)) or (isinstance(body, dict) and "raw" in body):
                raise SetupError(f"GET {api.base + path} -> {status} {short(body)} (not a JSON answer of the service: "
                                 f"is the Kong route registered and the pod Ready?)")

    # ---- stage 1: region + delivery stations
    def topology_base(self) -> None:
        reg = self.cfg["region"]
        region = self.find_region()
        if region:
            self.same(f"region {reg['code']}")
            rid = region["regionId"]
        else:
            out, body = self.write("CREATE", f"region {reg['code']}", self.nt, "POST", "/regions",
                                   {"code": reg["code"], "name": reg["name"]}, self.key("region", reg["code"]),
                                   ok=(201,), tolerate=("region-code-taken",))
            if out == "dry":
                rid = f"{DRY}region:{reg['code']}"
            elif out == "done":
                rid = body["regionId"]
            else:
                region = self.find_region()
                if not region:
                    raise StepError(f"region {reg['code']}: 409 region-code-taken but it is not listed")
                rid = region["regionId"]
        self.state["region_id"] = rid
        for ds in self.cfg["deliveryStations"]:
            try:
                self.station(ds, rid)
            except StepError as e:
                self.fail(str(e))

    def station(self, ds: dict, region_id: str) -> None:
        label = f"delivery station {ds['code']} (postal {ds['postalCode']})"
        node = self.find_station(ds, region_id)
        if node is None:
            body = {"nodeType": "DELIVERY_STATION", "operator": "NETWORK", "regionId": region_id,
                    "timezone": ds["timezone"],
                    "location": {"postalCode": ds["postalCode"], "countryCode": ds["countryCode"],
                                 "lat": ds.get("lat"), "lon": ds.get("lon")}}
            body["location"] = {k: v for k, v in body["location"].items() if v is not None}
            out, resp = self.write("CREATE", label, self.nt, "POST", "/nodes", body, self.key("ds", ds["code"]), ok=(201,))
            nid, status = (f"{DRY}ds:{ds['code']}", "PROPOSED") if out == "dry" else (resp["nodeId"], resp.get("status", "PROPOSED"))
            self.fresh = True
        else:
            nid, status = node["nodeId"], node["status"]
            self.same(label, status)
        self.ensure_active(label, nid, status)
        self.state["ds"][ds["code"]] = nid

    def ensure_active(self, label: str, node_id: str, status: str) -> None:
        if status == "ACTIVE":
            return
        if status != "PROPOSED":
            raise StepError(f"{label} is {status}: the seed activates only PROPOSED nodes (a suspension is an operator decision)")
        self.write("ACTIVATE", label, self.nt, "POST", f"/nodes/{q(node_id)}:activate", None,
                   self.key("activate", node_id), ok=(200,))
        self.fresh = True

    # ---- stage 2: vendor, fulfillment nodes, profiles
    def vendor(self) -> None:
        v = self.cfg["vendor"]
        if not self.state["region_id"]:
            raise Skip("region")
        acct = self.read(self.vc, f"/vendors/{q(v['vendorId'])}", allow_404=True)
        if acct is None:
            self.write("CREATE", f"vendor {v['vendorId']}", self.vc, "POST", "/vendors",
                       {"vendorId": v["vendorId"], "name": v["name"], "ackWindowMinutes": v["ackWindowMinutes"]},
                       self.key("vendor", v["vendorId"]), ok=(200, 201))
        elif acct.get("state") != "ACTIVE":
            raise StepError(f"vendor {v['vendorId']} is {acct.get('state')}: reinstate it (POST /vendors/{v['vendorId']}:reinstate)")
        else:
            self.same(f"vendor {v['vendorId']}", acct["state"])
        for fc in self.cfg["fulfillmentNodes"]:
            try:
                self.fulfillment_node(fc)
            except StepError as e:
                self.fail(str(e))

    def fulfillment_node(self, fc: dict) -> None:
        code, rid = fc["vendorNodeCode"], self.state["region_id"]
        label = f"fulfillment node {code} (vendor {self.vendor_id})"
        node = self.find_fc(fc)
        if node is None:
            body = {"vendorId": self.vendor_id, "vendorNodeCode": code, "nodeType": fc["nodeType"],
                    "subtype": fc.get("subtype"), "regionId": rid, "timezone": fc["timezone"],
                    "postalCode": fc["postalCode"], "countryCode": fc["countryCode"],
                    "lat": fc.get("lat"), "lon": fc.get("lon")}
            body = {k: v for k, v in body.items() if v is not None}
            self.vendor_write("CREATE", label, "/vendor/nodes", "POST", body, self.key("node", code),
                              tolerate_codes=("ErrVendorNodeCodeTaken",))
            if self.dry_run:
                node = {"nodeId": f"{DRY}fc:{code}", "status": "PROPOSED"}
            else:
                self.fresh = True
                node = self.find_fc(fc)
                if node is None:
                    raise StepError(f"{label}: the registration transaction ended without a live node in node-topology "
                                    f"(a RETIRED node holding vendorNodeCode {code}?)")
        else:
            self.same(label, f"adopted {node['nodeId']}, {node['status']}")
        nid = node["nodeId"]
        have = (node.get("operationalProfile") or {}).get("profileRevision", 0)
        want = fc["profile"]["profileRevision"]
        if have >= want:
            self.same(f"profile of {code}", f"revision {have}" + (f" > {want}: declared elsewhere, left alone" if have > want else ""))
        else:
            self.vendor_write("DECLARE", f"profile r{want} of {code}", f"/vendor/nodes/{q(nid)}/profile", "PUT",
                              {"vendorId": self.vendor_id, **fc["profile"]}, self.key("profile", code, str(want)),
                              tolerate_codes=("ErrStaleProfileRevision",))
        self.state["fc"][code] = nid

    # ---- stage 3: activation, lanes, service areas
    def topology_wire(self) -> None:
        for fc in self.cfg["fulfillmentNodes"]:
            try:
                self.wire_fulfillment_node(fc)
            except Skip as s:
                self.skip(f"{fc['vendorNodeCode']}: needs {s}")
            except StepError as e:
                self.fail(str(e))
        for ds in self.cfg["deliveryStations"]:
            for prefix in ds["serviceAreaPrefixes"]:
                try:
                    self.service_area(ds, prefix)
                except Skip as s:
                    self.skip(f"service area {prefix}: needs {s}")
                except StepError as e:
                    self.fail(str(e))

    def skip(self, msg: str) -> None:
        print(f"  SKIPPED  {msg}")
        self.skipped += 1

    def wire_fulfillment_node(self, fc: dict) -> None:
        code = fc["vendorNodeCode"]
        fid = self.state["fc"].get(code)
        if not fid:
            raise Skip(f"fulfillment node {code}")
        label = f"fulfillment node {code}"
        status = "PROPOSED" if is_dry(fid) else self.read(self.nt, f"/nodes/{q(fid)}")["status"]
        self.ensure_active(label, fid, status)
        lane = fc.get("lane")
        if not lane:
            return
        sid = self.state["ds"].get(lane["toStation"])
        if not sid:
            raise Skip(f"delivery station {lane['toStation']}")
        llabel = f"lane {code} -> {lane['toStation']} ({lane['mode']}, {lane['nominalTransitMinutes']} min)"
        if not (is_dry(fid) or is_dry(sid)) and self.open_lane(fid, sid):
            self.same(llabel)
            return
        self.write("CREATE", llabel, self.nt, "POST", "/lanes",
                   {"originNodeId": fid, "destinationNodeId": sid, "mode": lane["mode"],
                    "nominalTransitMinutes": lane["nominalTransitMinutes"]},
                   self.key("lane", code, lane["toStation"]), ok=(201,), tolerate=("duplicate-lane",))
        self.fresh = True

    def service_area(self, ds: dict, prefix: str) -> None:
        sid = self.state["ds"].get(ds["code"])
        if not sid:
            raise Skip(f"delivery station {ds['code']}")
        label = f"service area {prefix} -> {ds['code']}"
        current = None if is_dry(sid) else self.read(self.nt, f"/service-areas/{q(prefix)}", allow_404=True)
        if current and current.get("deliveryStationNodeId") == sid:
            self.same(label, f"version {current.get('assignmentVersion')}")
            return
        if current and not self.reassign:
            raise StepError(f"{label}: prefix is assigned to {current.get('deliveryStationNodeId')} "
                            f"(version {current.get('assignmentVersion')}); left alone, --reassign takes it over")
        version = (current or {}).get("assignmentVersion", 0) + 1
        self.write("ASSIGN" if current else "CREATE", label, self.nt, "PUT", f"/service-areas/{q(prefix)}",
                   {"deliveryStationNodeId": sid, "assignmentVersion": version},
                   self.key("area", prefix, str(version)), ok=(200,))

    # ---- stage 4: delivery waves
    def waves(self) -> None:
        self.settle()
        w = self.cfg["waves"]
        for ds in self.cfg["deliveryStations"]:
            sid = self.state["ds"].get(ds["code"])
            if not sid:
                self.skip(f"waves of {ds['code']}: needs delivery station {ds['code']}")
                continue
            tz = tzinfo(ds["timezone"])
            today = self.now.astimezone(tz).date()
            for i in range(w["days"]):
                day = today + dt.timedelta(days=i)
                induct, start, end = wave_times(day, tz, w)
                if end <= self.now:
                    continue
                label = f"wave {ds['code']} {day} window {start:%H:%MZ}-{end:%H:%MZ}, induct {induct:%H:%MZ}"
                try:
                    if not is_dry(sid):
                        have = self.read(self.lm, "/waves" + qs(stationNodeId=sid, serviceDate=day.isoformat())).get("items", [])
                        if any(parse_ts(x["inductCutoffAt"]) == induct and x.get("state") != "CANCELLED" for x in have):
                            self.same(label)
                            continue
                    self.write("CREATE", label, self.lm, "POST", "/waves",
                               {"stationNodeId": sid, "serviceDate": day.isoformat(), "inductCutoffAt": iso(induct),
                                "windowStart": iso(start), "windowEnd": iso(end), "stopCapacity": w["stopCapacity"]},
                               self.key("wave", sid, day.isoformat()), ok=(201,))
                except StepError as e:
                    self.fail(str(e))

    # ---- stage 5: catalogue + listings
    def catalog(self) -> None:
        have = self.catalog_by_title()
        for it in self.cfg["catalog"]:
            label = f"catalogue item {it['sku']}"
            try:
                found = have.get(it["title"])
                if found:
                    if found.get("state") != "ACTIVE":
                        raise StepError(f"{label}: exists but is {found.get('state')}; give the item a new title in the data file")
                    self.same(label, found["catalogItemId"])
                    self.state["items"][it["sku"]] = found["catalogItemId"]
                    continue
                body = {k: it[k] for k in ("title", "lengthMm", "widthMm", "heightMm", "weightG", "hazmat", "fragile")}
                out, resp = self.write("CREATE", label, self.oa, "POST", "/catalog-items", body, self.key("item", it["sku"]), ok=(201,))
                self.state["items"][it["sku"]] = f"{DRY}item:{it['sku']}" if out == "dry" else resp["catalogItemId"]
            except StepError as e:
                self.fail(str(e))

    def settle(self) -> None:
        """Give the event-fed views of last-mile-delivery / offer-availability a moment after nodes changed."""
        if self.fresh and not self.dry_run:
            self.sleep(self.settle_s)
        self.fresh = False

    def listings(self) -> None:
        self.settle()
        for fc in self.cfg["fulfillmentNodes"]:
            code, fid = fc["vendorNodeCode"], self.state["fc"].get(fc["vendorNodeCode"])
            if not fid:
                self.skip(f"listings on {code}: needs fulfillment node {code}")
                continue
            have = {} if is_dry(fid) else {l["catalogItemId"]: l for l in self.pages(self.oa, "/listings", {"nodeId": fid}, "listings")}
            for it in self.cfg["catalog"]:
                label = f"listing {it['sku']} @ {code}"
                cid = self.state["items"].get(it["sku"])
                if not cid:
                    self.skip(f"{label}: needs catalogue item {it['sku']}")
                    continue
                try:
                    cur = have.get(cid)
                    if cur:
                        self.same(label, f"{cur['listingId']}, {cur['state']}")
                        self.state["listings"][(code, it["sku"])] = cur["listingId"]
                        continue
                    out, resp = self.write("CREATE", label, self.oa, "POST", "/listings", {"catalogItemId": cid, "nodeId": fid},
                                           self.key("listing", fid, cid), ok=(201,), tolerate=("duplicate-listing",))
                    if out == "dry":
                        self.state["listings"][(code, it["sku"])] = f"{DRY}listing:{code}:{it['sku']}"
                    elif out == "done":
                        self.state["listings"][(code, it["sku"])] = resp["listingId"]
                    else:
                        again = {l["catalogItemId"]: l for l in self.pages(self.oa, "/listings", {"nodeId": fid}, "listings")}
                        self.state["listings"][(code, it["sku"])] = again[cid]["listingId"]
                except (StepError, KeyError) as e:
                    self.fail(str(e) if isinstance(e, StepError) else f"{label}: listing not found after 409")

    # ---- stage 6: inventory feed (through the Vendor API, like a vendor)
    def inventory(self) -> None:
        for fc in self.cfg["fulfillmentNodes"]:
            code, fid = fc["vendorNodeCode"], self.state["fc"].get(fc["vendorNodeCode"])
            try:
                if not fid:
                    raise Skip(f"fulfillment node {code}")
                self.feed(fc, code, fid)
            except Skip as s:
                self.skip(f"inventory of {code}: needs {s}")
            except StepError as e:
                self.fail(str(e))

    def feed(self, fc: dict, code: str, fid: str) -> None:
        listings = [] if is_dry(fid) else self.pages(self.oa, "/listings", {"nodeId": fid}, "listings")
        by_id = {l["listingId"]: l for l in listings}
        targets = {}         # listingId -> quantity to declare
        for it in self.cfg["catalog"]:
            lid = self.state["listings"].get((code, it["sku"]))
            if not lid:
                raise Skip(f"listing {it['sku']}")
            cur = by_id.get(lid)
            fed = bool(cur and (cur.get("availability") or {}).get("feedId"))
            if self.restock or not fed:
                targets[lid] = it["availableQty"]
        label = f"inventory feed of {code}: {len(targets)} listing(s) to {sorted(set(targets.values()))}"
        if not targets:
            self.same(f"inventory of {code}", "every seeded listing already carries a feed; --restock to refeed")
            return
        if self.dry_run:
            self.write("FEED", label, self.vc, "POST", "/vendor/inventory", {}, "")
            return
        # fullUpdate zeroes every listing the feed omits: carry the node's other listings at their current values
        lines = [{"listingId": lid, "availableQty": qty, "basis": "PHYSICAL"} for lid, qty in sorted(targets.items())]
        for l in sorted(listings, key=lambda x: x["listingId"]):
            if l["listingId"] not in targets:
                a = l.get("availability") or {}
                lines.append({"listingId": l["listingId"], "availableQty": a.get("availableQty", 0), "basis": a.get("basis", "UNKNOWN")})
        self.vendor_write("FEED", label, "/vendor/inventory", "POST",
                          {"vendorId": self.vendor_id, "nodeId": fid, "fullUpdate": True, "asOf": iso(self.now), "lines": lines},
                          self.key("inventory", fid))

    # ---- stage 7: delivery-promise (read only)
    def policy(self) -> None:
        pol = self.read(self.dp, "/promise-policies/current")
        print(f"  exists   promise policy {pol.get('policyVersion')} "
              f"({'built-in default in code' if pol.get('version') == 0 else 'published'}): nothing to seed")

    def seed(self) -> None:
        stages = [
            ("node-topology: region + delivery stations", self.topology_base),
            ("vendor-connectivity: vendor, fulfillment nodes, profiles", self.vendor),
            ("node-topology: activation, lanes, service areas", self.topology_wire),
            ("last-mile-delivery: delivery waves", self.waves),
            ("offer-availability: catalogue items", self.catalog),
            ("offer-availability: listings", self.listings),
            ("vendor-connectivity: inventory feed", self.inventory),
            ("delivery-promise: policy", self.policy),
        ]
        for title, fn in stages:
            print(f"\n[{title}]")
            try:
                fn()
            except Skip as s:
                self.skip(f"needs {s}")
            except (StepError, SetupError) as e:
                self.fail(str(e))

    # ---- verification (GET only; --quote adds one POST, opt-in)
    def verify(self, quote=False) -> list:
        rows: list = []

        def check(name: str, fn) -> None:
            try:
                ok, detail = fn()
            except (StepError, SetupError, KeyError, TypeError) as e:
                ok, detail = False, f"{type(e).__name__}: {e}"
            rows.append((name, bool(ok), detail))

        v = self.cfg["vendor"]["vendorId"]
        check(f"vendor {v} ACTIVE", lambda: self._vendor_ok(v))
        region_id = []

        def region():
            r = self.find_region()
            if r:
                region_id.append(r["regionId"])
            return bool(r), f"{self.cfg['region']['code']} = {r['regionId']}" if r else "absent"

        check(f"region {self.cfg['region']['code']}", region)
        stations = {}
        for ds in self.cfg["deliveryStations"]:
            def st(ds=ds):
                n = self.find_station(ds, region_id[0]) if region_id else None
                if n:
                    stations[ds["code"]] = n["nodeId"]
                return bool(n) and n["status"] == "ACTIVE", f"{n['nodeId']} {n['status']}" if n else "absent"
            check(f"delivery station {ds['code']} ACTIVE", st)
            for prefix in ds["serviceAreaPrefixes"]:
                def area(ds=ds, prefix=prefix):
                    a = self.read(self.nt, f"/service-areas/{q(prefix)}", allow_404=True)
                    if not a:
                        return False, "unassigned"
                    return a.get("deliveryStationNodeId") == stations.get(ds["code"]), \
                        f"station {a.get('deliveryStationNodeId')}, version {a.get('assignmentVersion')}"
                check(f"service area {prefix} -> {ds['code']}", area)
        for fc in self.cfg["fulfillmentNodes"]:
            self._verify_fc(fc, stations, check)
        for ds in self.cfg["deliveryStations"]:
            check(f"open waves at {ds['code']} (next 3 days)", lambda ds=ds: self._waves_ok(ds, stations))
        check("promise policy readable", lambda: self._policy_ok())
        if quote:
            check("delivery quote answers", lambda: self._quote_ok())
        return rows

    def _vendor_ok(self, v: str):
        acct = self.read(self.vc, f"/vendors/{q(v)}", allow_404=True)
        return bool(acct) and acct.get("state") == "ACTIVE", f"{acct['state']}, ackWindow {acct['ackWindowMinutes']} min" if acct else "absent"

    def _verify_fc(self, fc: dict, stations: dict, check) -> None:
        code, found = fc["vendorNodeCode"], {}

        def node():
            n = self.find_fc(fc)
            if n:
                found["id"] = n["nodeId"]
            return bool(n) and n["status"] == "ACTIVE", f"{n['nodeId']} {n['status']}" if n else "absent"

        check(f"node {code} ACTIVE (node-topology)", node)

        def view():
            if "id" not in found:
                return False, "no node"
            n = self.read(self.vc, f"/vendor/nodes/{q(found['id'])}" + qs(vendorId=self.vendor_id), allow_404=True)
            if not n:
                return False, "not in the vendor's node view"
            want = fc["profile"]["profileRevision"]
            return (n.get("profileRevision") or 0) >= want, \
                f"profileRevision {n.get('profileRevision')} (seed {want}), handling {n.get('handlingTimeMinutes')} min, {n.get('status')}"

        check(f"node {code} profile (vendor API)", view)
        lane = fc.get("lane")
        if lane:
            def lane_ok():
                sid = stations.get(lane["toStation"])
                if "id" not in found or not sid:
                    return False, "node or station missing"
                l = self.open_lane(found["id"], sid)
                return bool(l), f"{l['laneId']} {l['nominalTransitMinutes']} min" if l else "no OPEN lane"
            check(f"lane {code} -> {lane['toStation']} OPEN", lane_ok)

        def pickups():
            if "id" not in found:
                return False, "no node"
            deps = self.read(self.lh, "/departures" + qs(origin=found["id"], limit=50)).get("departures", [])
            pick = [d for d in deps if d.get("kind") == "PICKUP" and d.get("state") == "SCHEDULED"]
            return bool(pick), f"{len(pick)} SCHEDULED pickup departure(s), generated by linehaul-transportation"

        check(f"pickup departures of {code}", pickups)

        def stock():
            if "id" not in found:
                return False, "no node"
            cat = self.catalog_by_title()
            by_item = {l["catalogItemId"]: l for l in self.pages(self.oa, "/listings", {"nodeId": found["id"]}, "listings")}
            bad, parts = [], []
            for it in self.cfg["catalog"]:
                l = by_item.get((cat.get(it["title"]) or {}).get("catalogItemId"))
                a = (l or {}).get("availability") or {}
                good = bool(l) and l.get("state") == "LIVE" and a.get("availableQty", 0) > 0
                parts.append(f"{it['sku']}={a.get('availableQty', '-')}" + ("" if good else f"({(l or {}).get('state', 'no listing')})"))
                if not good:
                    bad.append(it["sku"])
            return not bad, "availableQty " + ", ".join(parts)

        check(f"listings of {code} LIVE with stock", stock)

    def _waves_ok(self, ds: dict, stations: dict):
        sid = stations.get(ds["code"])
        if not sid:
            return False, "no station"
        tz, n = tzinfo(ds["timezone"]), 0
        today = self.now.astimezone(tz).date()
        for i in range(3):
            items = self.read(self.lm, "/waves" + qs(stationNodeId=sid, serviceDate=(today + dt.timedelta(days=i)).isoformat())).get("items", [])
            n += sum(1 for x in items if x.get("state") == "OPEN")
        return n > 0, f"{n} OPEN wave(s)"

    def _policy_ok(self):
        pol = self.read(self.dp, "/promise-policies/current")
        return True, f"{pol.get('policyVersion')}, offer TTL {pol.get('offerTtlMinutes')} min"

    def _quote_ok(self):
        cat = self.catalog_by_title()
        item = (cat.get(self.cfg["catalog"][0]["title"]) or {}).get("catalogItemId")
        if not item:
            return False, "first seeded item is not in the catalogue"
        prefix = self.cfg["deliveryStations"][0]["serviceAreaPrefixes"][0]
        status, body = self.dp.call("POST", "/delivery-offers:quote",
                                    {"destinationPostalPrefix": prefix, "lines": [{"catalogItemId": item, "quantity": 1}]})
        if status != 200 or not isinstance(body, dict):
            return False, f"POST /delivery-offers:quote -> {status} {short(body)}"
        tiers = sorted({o["tier"] for o in body.get("offers", [])})
        why = ", ".join(f"{u['tier']}={u['constraint']}" for u in body.get("unavailable", []))
        return bool(tiers), f"offers: {', '.join(tiers) or 'none'}" + (f"; unavailable: {why}" if why else "")


def print_table(rows: list) -> bool:
    width = max((len(r[0]) for r in rows), default=10)
    print(f"\n{'CHECK':<{width}}  RESULT  DETAIL")
    for name, ok, detail in rows:
        print(f"{name:<{width}}  {'PASS' if ok else 'FAIL':<6}  {detail}")
    passed = sum(1 for r in rows if r[1])
    print(f"\nverify: {passed}/{len(rows)} checks passed")
    return passed == len(rows)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base-url", default=os.environ.get("RETAIL_NETWORK_BASE_URL", DEFAULT_BASE_URL),
                    help="Kong base; each context is <base-url>/<context> (default %(default)s)")
    ap.add_argument("--data", default=DATA_FILE, help="seed data file (default scripts/data/retail-network-seed.json)")
    ap.add_argument("--dry-run", action="store_true", help="print the plan (GETs only), write nothing")
    ap.add_argument("--verify", action="store_true", help="read-only PASS/FAIL table, write nothing")
    ap.add_argument("--quote", action="store_true", help="with --verify: also POST one delivery quote (persists a short-lived offer)")
    ap.add_argument("--no-verify", action="store_true", help="skip the verification that follows a seed run")
    ap.add_argument("--restock", action="store_true", help="refeed the seeded quantities even for listings that already carry a feed")
    ap.add_argument("--reassign", action="store_true", help="take over a postal prefix assigned to another station (version + 1)")
    ap.add_argument("--settle-seconds", type=float, default=5.0, help="wait after creating/activating nodes for the event-fed views (default 5)")
    ap.add_argument("--tx-timeout-seconds", type=float, default=60.0, help="longest wait for one asynchronous vendor transaction (default 60)")
    ap.add_argument("--tx-poll-seconds", type=float, default=1.0, help="transaction polling interval (default 1)")
    ap.add_argument("--now", help=argparse.SUPPRESS)      # pin the clock (ISO 8601): tests, reproducible plans
    args = ap.parse_args(argv)

    try:
        cfg = load_config(args.data)
        now = parse_ts(args.now) if args.now else dt.datetime.now(dt.timezone.utc).replace(microsecond=0)
        apis = {c: Api(f"{args.base_url.rstrip('/')}/{c}") for c in CONTEXTS}
        seeder = Seeder(cfg, apis, now=now, dry_run=args.dry_run, restock=args.restock, reassign=args.reassign,
                        settle_s=args.settle_seconds, tx_timeout_s=args.tx_timeout_seconds, tx_poll_s=args.tx_poll_seconds)
        seeder.preflight()
    except (SetupError, ValueError) as e:
        print(f"seed-retail-network: {e}", file=sys.stderr)
        return 2

    if args.verify:
        try:
            return 0 if print_table(seeder.verify(quote=args.quote)) else 1
        except SetupError as e:
            print(f"seed-retail-network: {e}", file=sys.stderr)
            return 2

    seeder.seed()
    c = seeder.counts
    w = "would be " if args.dry_run else ""
    print(f"\nseed-retail-network: {c['created']} {w}created, {c['updated']} {w}updated, {c['unchanged']} unchanged, "
          f"{len(seeder.failures)} failed, {seeder.skipped} skipped")
    if seeder.failures:
        print("failures:\n  " + "\n  ".join(seeder.failures))
    rc = 1 if seeder.failures or seeder.skipped else 0
    if not args.dry_run and not args.no_verify:
        rows = []
        for attempt in range(4):        # the node views are event-fed: give them a moment before calling it a FAIL
            try:
                rows = seeder.verify()
            except SetupError as e:
                print(f"seed-retail-network: {e}", file=sys.stderr)
                return 1
            if all(r[1] for r in rows) or attempt == 3:
                break
            seeder.sleep(args.settle_seconds)
        rc = rc if print_table(rows) else 1
    return rc


if __name__ == "__main__":
    sys.exit(main())
